'use strict';
const assert=require('assert'),fixture=require('./fixtures/diagnostic-runtime.cjs');
let f=fixture();
// A legacy ON preference must not authorize statistics in a new session.
f.nodes.diagnosticsSwitch={checked:true};f.nodes.performanceStatsSwitch={checked:true};
f.d.start();f.d.connected();f.d.sample(f.sample(1));
assert.equal(f.generations.length+f.timers.size+f.frames.size,0,'new sessions must remain uninstrumented');
f.d.finish();assert.equal(f.storage.size,0,'a session never activated leaves no report');
f=fixture();f.d.start({game:'Artificial game',config:{pacing:true,bitrate:30}});f.d.connected();
f.advance(10000);assert(f.d.activate());assert.equal(f.frames.size,1);assert.equal(f.timers.size,1);
const gen=f.generations.at(-1); assert(gen>0);assert(f.d.isRecording());
assert(!f.d.activate(),'repeated activation does not duplicate observers');
f.frame(100,1);f.frame(116.667,2);f.frame(183.334,3);f.frame(250.001,7);
f.d.sample(f.sample(gen));f.advance(2000);f.d.sample(f.sample(gen,{ms:1000,rx:30,sub:30,rtt:9}));
const stale=[...f.frames.values()][0];f.video.drops+=2;f.c._mlAudioStats.underruns+=1;f.tick();
f.d.finish('Exit code 0');f.d.finish('duplicate');
assert.equal(f.timers.size+f.frames.size+f.listeners.size,0);
const records=f.c.DiagnosticHistory.create(f.c.localStorage).list().records;
assert.equal(records.length,1);const r=records[0];
assert(r.durationMs>r.recordedMs,'late activation has partial coverage');
assert.equal(r.rows.length,9);assert(r.details.length>4);
assert.equal(r.metrics.fpsReceived,50,'duration-weighted counts');
assert.equal(r.metrics.rtt,5,'duration-weighted RTT');
assert.equal(r.metrics.audioUnderruns,1);assert.equal(r.metrics.browserDrops,2);
assert(r.metrics.presentMax>66,'retain long presentation intervals');
assert.equal(r.metrics.coalesced,1,'callback coalescence is not a dropped frame');
assert.equal(r.config.pacing,true);assert.equal(r.game,'Artificial game');
const n=f.events.length;stale(500,{presentedFrames:10});f.d.sample(f.sample(gen));
assert.equal(f.events.length,n);assert.equal(f.frames.size,0);
f.d.start();f.d.connected();assert(!f.d.isRecording());f.d.finish();
assert.equal(f.c.DiagnosticHistory.create(f.c.localStorage).list().records.length,1,'new unarmed session preserves history');
f.d.start();f.d.connected();f.d.activate();const gen2=f.generations.at(-1);
assert(gen2!==gen);f.d.sample(f.sample(gen));f.advance(1000);f.d.finish();
const empty=f.c.DiagnosticHistory.create(f.c.localStorage).list().records[0];
assert.equal(empty.metrics.fpsReceived,null,'stale windows cannot populate next session');
const denied=fixture();denied.d.start();denied.d.connected();denied.d.activate();denied.advance(1000);
Object.defineProperty(denied.c,'localStorage',{get(){throw Error('disabled storage');},configurable:true});
assert.doesNotThrow(()=>denied.d.finish('Exit code 0'),'storage access failure cannot interrupt stream teardown');
assert.equal(denied.timers.size+denied.frames.size+denied.listeners.size,0);
assert(denied.events.some(e=>String(e).startsWith('Could not save diagnosis')));
console.log('diagnostic_session_test: explicit activation, late coverage, shared observers, aggregates and generations PASS');
